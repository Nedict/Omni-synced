//! `cargo xtask solver-oracle`: replay the solver-behaviour cases
//! (`plan/fusion/solver-oracle/<case>/case.json`, local) with `solvecraft-cli solver-oracle`,
//! compare each dimension edit with Fusion's `measure.json` and write `docs/solver-oracle.md`
//! (counts and our comparison only, no Fusion data). Fails when an edit is `mirrored`,
//! `different` or `we_refused` without an entry in `xtask/data/solver-oracle-known.tsv`.
//! Cases without measurements are listed as not measured yet (with how many edits SolveCraft
//! took); without any case data it says so, writes nothing and succeeds: the data is local.

use std::path::{Path, PathBuf};

use serde_json::Value;

const KNOWN: &str = "xtask/data/solver-oracle-known.tsv";
const DOC: &str = "docs/solver-oracle.md";

/// Classes in table order (as `solvecraft-cli solver-oracle` names them) and their headings.
const CLASSES: [(&str, &str); 6] = [
    ("same", "same"),
    ("mirrored", "mirrored"),
    ("different", "different"),
    ("we_refused", "we refused"),
    ("fusion_refused", "Fusion refused"),
    ("both_refused", "both refused"),
];

/// Classes that need an explanation in the allow-list.
const GATED: [&str; 3] = ["mirrored", "different", "we_refused"];

pub const INTRO: &str = "# Solver oracle\n\n\
Generated by `cargo xtask solver-oracle`. Each case is a sketch with named dimensions and a run of dimension edits \
(`plan/fusion/solver-oracle/<case>/case.json`, local, not committed). Fusion built each case and recorded, after every \
edit, where each point landed and whether the values took (`measure.json`, local, never committed). SolveCraft builds the \
same sketch with its sketch commands, applies the same edits in the same order (all values of an edit in one recompute \
with `parameters.import`, or one `parameters.change` after another where Fusion applied them one by one) and compares:\n\n\
- **same**: every point within 1e-3 mm of Fusion's;\n\
- **mirrored**: both solved, and three mutually related points (dimensioned, joined by a line or arc, or both fixed) turn \
the other way, or a horizontal/vertical offset or line points the other way;\n\
- **different**: both solved, another placement with the same orientations;\n\
- **we refused** / **Fusion refused**: only one of them took the values (SolveCraft: once all of an edit's values are \
applied, the sketch does not solve or does not measure them; the edit is then undone before the next one, as Fusion keeps \
the values it held. Fusion: the parameters do not hold the requested values, whatever the sketch's health); **both refused**.\n\n\
Mirrored, different and we-refused edits need a reason in `xtask/data/solver-oracle-known.tsv` (case, edit, reason), \
or the task fails.\n";

/// An allow-list entry: an edit (or every edit, `*`) whose difference is expected, and why.
#[derive(Debug, PartialEq)]
pub struct Known {
    case: String,
    edit: Option<u64>,
    reason: String,
}

/// Parse the allow-list: `case \t edit|* \t reason`, `#` comments.
pub fn parse_known(text: &str) -> Result<Vec<Known>, String> {
    let mut out: Vec<Known> = Vec::new();
    for (i, l) in text.lines().enumerate().filter(|(_, l)| !l.trim().is_empty() && !l.starts_with('#')) {
        let cols: Vec<&str> = l.split('\t').map(str::trim).collect();
        let [case, edit, reason] = cols.as_slice() else {
            return Err(format!("{KNOWN}:{}: want case, edit, reason (tab separated)", i + 1));
        };
        let edit = if *edit == "*" { None } else { Some(edit.parse().map_err(|_| format!("{KNOWN}:{}: edit must be a number or *", i + 1))?) };
        if reason.is_empty() {
            return Err(format!("{KNOWN}:{}: the reason is empty", i + 1));
        }
        if out.iter().any(|k| k.case == *case && k.edit == edit) {
            return Err(format!("{KNOWN}:{}: duplicate row for {case} edit {}", i + 1, edit_label(edit)));
        }
        out.push(Known { case: case.to_string(), edit, reason: reason.to_string() });
    }
    Ok(out)
}

/// An allow-list row's edit as written: its number, or `*` for every edit.
fn edit_label(edit: Option<u64>) -> String {
    edit.map_or("*".to_string(), |e| e.to_string())
}

/// Whether a CLI result compared the case with Fusion's measurements.
fn is_measured(r: &Value) -> bool {
    r["measured"].as_bool() == Some(true)
}

/// Text for a table cell: no column breaks, no line breaks.
fn cell(s: &str) -> String {
    s.replace('|', "/").replace(['\n', '\r'], " ")
}

/// The table, the differences and the allow-list check for `results` (the CLI's JSON, measured
/// and unmeasured cases). Returns the markdown and the problems that fail the task.
pub fn render(results: &[Value], known: &[Known]) -> (String, Vec<String>) {
    let mut errors = Vec::new();
    let mut unexplained = Vec::new();
    let mut used = vec![false; known.len()];
    let mut totals = [0u64; CLASSES.len()];
    let mut table = format!(
        "| Case | Edits | {} | Notes |\n|---|---|{}---|\n",
        CLASSES.iter().map(|(_, h)| *h).collect::<Vec<_>>().join(" | "),
        "---|".repeat(CLASSES.len())
    );
    let mut diffs = String::new();
    let (mut measured, mut unmeasured_edits) = (0usize, 0u64);
    // Cases compared with Fusion (measured and replayed): only there can a row be stale.
    let mut compared = std::collections::BTreeSet::new();
    for r in results {
        let raw_case = r["case"].as_str().unwrap_or("");
        let case = cell(raw_case);
        let edits = r["edits"].as_u64().unwrap_or(0);
        let error = r["error"].as_str().map(cell);
        if let Some(e) = &error {
            errors.push(format!("{case}: {e}"));
        }
        if !is_measured(r) {
            unmeasured_edits += edits;
            let took = r["took"].as_u64().map(|t| format!("; SolveCraft took {t}")).unwrap_or_default();
            let note = error.unwrap_or_else(|| format!("not measured in Fusion yet{took}"));
            table += &format!("| {case} | {edits} |{} {note} |\n", " – |".repeat(CLASSES.len()));
            continue;
        }
        measured += 1;
        if error.is_none() {
            compared.insert(raw_case);
        }
        let counts: Vec<u64> = CLASSES.iter().map(|(c, _)| r["counts"][c].as_u64().unwrap_or(0)).collect();
        for (t, n) in totals.iter_mut().zip(&counts) {
            *t += n;
        }
        table += &format!(
            "| {case} | {edits} | {} | {} |\n",
            counts.iter().map(u64::to_string).collect::<Vec<_>>().join(" | "),
            error.unwrap_or_default()
        );
        for e in r["results"].as_array().into_iter().flatten() {
            let class = e["class"].as_str().unwrap_or("");
            if class == "same" || class == "both_refused" {
                continue;
            }
            let edit = e["edit"].as_u64().unwrap_or(0);
            // Every matching row is in use; the reason shown is the edit's own row before the
            // case's `*` row.
            let mut reason_of = None;
            for (k, u) in known.iter().zip(used.iter_mut()) {
                if k.case == raw_case && k.edit.is_none_or(|n| n == edit) {
                    *u = true;
                    if reason_of.is_none() || k.edit.is_some() {
                        reason_of = Some(k);
                    }
                }
            }
            let reason = match (reason_of, GATED.contains(&class)) {
                (Some(k), _) => cell(&k.reason),
                (None, true) => {
                    unexplained.push(format!("{raw_case} edit {edit}: {class} without a reason in {KNOWN}"));
                    "**unexplained**".to_string()
                }
                (None, false) => String::new(),
            };
            diffs += &format!("| {case} | {edit} | {class} | {} | {reason} |\n", cell(e["detail"].as_str().unwrap_or("")));
        }
    }
    let edits: u64 = totals.iter().sum();
    let summary: Vec<String> = CLASSES.iter().zip(totals).map(|((_, h), n)| format!("{h} {n}")).collect();
    let plural = |n: usize, what: &str| format!("{n} {what}{}", if n == 1 { "" } else { "s" });
    let headline = if measured == 0 {
        format!("**No Fusion measurements yet** ({}, {unmeasured_edits} edits).", plural(results.len(), "case"))
    } else {
        format!("**{edits} edits in {measured} measured cases: {}.**", summary.join(", "))
    };
    let mut md = format!("{INTRO}\n{headline} {} unexplained, {}.\n\n{table}", unexplained.len(), plural(errors.len(), "replay error"));
    if !diffs.is_empty() {
        md += &format!("\n## Differences\n\n| Case | Edit | Class | What differs | Reason |\n|---|---|---|---|---|\n{diffs}");
    }
    let stale: Vec<String> = known
        .iter()
        .zip(&used)
        .filter(|(k, u)| !**u && compared.contains(k.case.as_str()))
        .map(|(k, _)| format!("| {} | {} | {} |\n", cell(&k.case), edit_label(k.edit), cell(&k.reason)))
        .collect();
    if !stale.is_empty() {
        md += &format!("\n## Allow-list entries no longer needed\n\n| Case | Edit | Reason |\n|---|---|---|\n{}", stale.concat());
    }
    errors.extend(unexplained);
    (md, errors)
}

pub fn run(root: &Path) -> Result<(), String> {
    let dir = root.join("plan/fusion/solver-oracle");
    let Ok(entries) = std::fs::read_dir(&dir) else {
        println!("solver-oracle: no cases in {} (the data is local); nothing to compare", dir.display());
        return Ok(());
    };
    let mut cases: Vec<PathBuf> = entries.flatten().map(|e| e.path()).filter(|p| p.join("case.json").is_file()).collect();
    if cases.is_empty() {
        println!("solver-oracle: no cases in {}; nothing to compare", dir.display());
        return Ok(());
    }
    cases.sort();
    let known = parse_known(&std::fs::read_to_string(root.join(KNOWN)).map_err(|e| format!("{KNOWN}: {e}"))?)?;
    let mut cmd = crate::cargo();
    cmd.args(["run", "-q", "--release", "-p", "solvecraft-cli", "--", "solver-oracle", "--json"]);
    cmd.args(&cases);
    let out = cmd.output().map_err(|e| format!("solvecraft-cli: {e}"))?;
    let results: Vec<Value> =
        serde_json::from_slice(&out.stdout).map_err(|e| format!("solver-oracle JSON: {e}\n{}", String::from_utf8_lossy(&out.stderr)))?;
    let (md, problems) = render(&results, &known);
    std::fs::write(root.join(DOC), md).map_err(|e| format!("{DOC}: {e}"))?;
    let measured = results.iter().filter(|r| is_measured(r)).count();
    if measured == 0 {
        println!("solver-oracle: no measure.json in {} yet (run the Fusion script, see its README.md); case list → {DOC}", dir.display());
    } else {
        println!("solver-oracle: {measured} measured case(s), {} problem(s) → {DOC}", problems.len());
    }
    if problems.is_empty() { Ok(()) } else { Err(problems.join("\n")) }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn allow_list_parses_and_rejects_bad_rows() {
        let k = parse_known("# comment\n\n05-linkage\t3\tfold refused by policy\n06-x\t*\twhy\n").unwrap();
        assert_eq!(k.len(), 2);
        assert_eq!(k[0], Known { case: "05-linkage".into(), edit: Some(3), reason: "fold refused by policy".into() });
        assert_eq!(k[1].edit, None);
        assert!(parse_known("a\tb\treason\n").is_err());
        assert!(parse_known("a\t1\n").is_err());
        assert!(parse_known("a\t1\t \n").is_err());
    }

    #[test]
    fn a_duplicate_allow_list_row_is_an_error() {
        let e = parse_known("a\t1\tone\nb\t1\tother case\na\t1\tagain\n").unwrap_err();
        assert!(e.contains(":3:") && e.contains("duplicate"), "{e}");
        assert!(parse_known("a\t*\tone\na\t*\ttwo\n").is_err());
        assert!(parse_known("a\t*\tall\na\t1\tthis one\n").is_ok());
    }

    fn result(case: &str, classes: &[&str]) -> Value {
        let mut counts = json!({});
        for c in classes {
            counts[*c] = json!(counts[*c].as_u64().unwrap_or(0) + 1);
        }
        let results: Vec<Value> = classes.iter().enumerate().map(|(i, c)| json!({"edit": i, "class": c, "detail": "C is 3 mm away"})).collect();
        json!({"case": case, "measured": true, "edits": classes.len(), "counts": counts, "results": results})
    }

    fn unmeasured(case: &str, edits: u64, took: u64) -> Value {
        json!({"case": case, "measured": false, "edits": edits, "took": took})
    }

    #[test]
    fn unexplained_disagreements_fail_and_allow_listed_ones_pass() {
        let results = [
            result("01-tri", &["same", "mirrored", "fusion_refused", "both_refused"]),
            result("05-link", &["we_refused", "different"]),
            unmeasured("07-offset", 16, 16),
        ];
        let known = parse_known("05-link\t*\tfold refused by policy\n").unwrap();
        let (md, problems) = render(&results, &known);
        assert_eq!(problems, vec!["01-tri edit 1: mirrored without a reason in xtask/data/solver-oracle-known.tsv".to_string()]);
        assert!(md.contains("| 01-tri | 1 | mirrored | C is 3 mm away | **unexplained** |"), "{md}");
        assert!(md.contains("| 05-link | 0 | we_refused | C is 3 mm away | fold refused by policy |"), "{md}");
        assert!(md.contains("| 01-tri | 2 | fusion_refused | C is 3 mm away |  |"), "{md}");
        assert!(!md.contains("both_refused |"), "{md}");
        assert!(md.contains("| 07-offset | 16 | – | – | – | – | – | – | not measured in Fusion yet; SolveCraft took 16 |"), "{md}");
        assert!(
            md.contains(
                "**6 edits in 2 measured cases: same 1, mirrored 1, different 1, we refused 1, Fusion refused 1, both refused 1.** 1 unexplained, 0 replay errors."
            ),
            "{md}"
        );
    }

    #[test]
    fn a_specific_allow_list_row_beats_the_case_wildcard_and_both_count_as_used() {
        let results = [result("05-link", &["we_refused", "different"])];
        let known = parse_known("05-link\t*\tfold refused by policy\n05-link\t1\tthe other assembly of the linkage\n").unwrap();
        let (md, problems) = render(&results, &known);
        assert!(problems.is_empty(), "{problems:?}");
        assert!(md.contains("| 05-link | 1 | different | C is 3 mm away | the other assembly of the linkage |"), "{md}");
        assert!(md.contains("| 05-link | 0 | we_refused | C is 3 mm away | fold refused by policy |"), "{md}");
        assert!(!md.contains("no longer needed"), "{md}");
    }

    #[test]
    fn a_stale_allow_list_entry_is_listed_but_not_for_a_case_that_did_not_replay() {
        let known = parse_known("02-arm\t0\twas mirrored before the seed\n").unwrap();
        let (md, problems) = render(&[result("02-arm", &["same"])], &known);
        assert!(problems.is_empty());
        assert!(md.contains("## Allow-list entries no longer needed"), "{md}");

        let mut broken = result("02-arm", &[]);
        broken["error"] = json!("the initial sketch differs from Fusion's");
        let (md, problems) = render(&[broken], &known);
        assert_eq!(problems.len(), 1);
        assert!(!md.contains("no longer needed"), "{md}");
        assert!(md.contains("0 unexplained, 1 replay error."), "{md}");
    }

    #[test]
    fn cells_keep_the_table_whole() {
        assert_eq!(cell("a|b\nc\r\nd"), "a/b c  d");
        let mut r = result("01|tri\nx", &["mirrored"]);
        r["results"][0]["detail"] = json!("turn A,B,C\n(far)");
        let (md, _) = render(&[r], &[]);
        assert!(md.contains("| 01/tri x | 0 | mirrored | turn A,B,C (far) | **unexplained** |"), "{md}");
    }

    #[test]
    fn nothing_measured_still_lists_the_cases() {
        let (md, problems) = render(&[unmeasured("01-triangle-apex", 24, 24), unmeasured("04-bracket", 24, 13)], &[]);
        assert!(problems.is_empty());
        assert!(md.starts_with(INTRO), "{md}");
        assert!(md.contains("**No Fusion measurements yet** (2 cases, 48 edits)."), "{md}");
        assert!(md.contains("| 04-bracket | 24 |"), "{md}");
    }
}
