#!/usr/bin/env python3
"""Generate the SolidCraft `swconst` interop enums from the ModelForge swconst assembly.

The ModelForge C# workspace compiles against `ModelForge.Interop.swconst.dll`. To let that same
C# compile and run against SolidCraft we reproduce the constant enums with their exact numeric
values, read straight out of the original assembly's .NET metadata (never from documentation, so
there is no licence concern: these are the public SolidWorks constants the workspace was built
with).

Usage:
    python3 tools/gen-swconst.py [--dll PATH] [--out DIR]

Defaults: the DLL from the ModelForge snapshot, output to csharp/SolidCraft.Interop/swconst.
Requires the `dnfile` package (pip install dnfile).
"""
import argparse
import os
import struct
import sys

try:
    import dnfile
except ImportError:  # a clear message beats a traceback
    sys.exit("gen-swconst: pip install dnfile")

DEFAULT_DLL = (
    "/Users/kevin/Desktop/parallels-recovery/qemu/archive/solidworks-wine-repro"
    "/qemu/runtime/solidworks-wine/workspace-builds/64166479807f/ModelForge.Interop.swconst.dll"
)


def load_enums(path):
    pe = dnfile.dnPE(path)
    md = pe.net.mdtables
    fields = md.Field.rows

    const_by_field = {}
    for c in md.Constant.rows:
        if c.Parent.table is not md.Field:
            continue
        const_by_field[c.Parent.row_index] = c

    def number(c):
        b = c.Value.value
        fmt = {8: "<i", 9: "<I", 6: "<b", 2: "<B", 10: "<h", 11: "<H"}.get(c.Type)
        if fmt is None:
            return None
        try:
            return struct.unpack(fmt, b[: struct.calcsize(fmt)])[0]
        except struct.error:
            return None

    out = []
    for td in md.TypeDef.rows:
        name = str(td.TypeName)
        if not (name.startswith("sw") and name.endswith("_e")):
            continue
        members = []
        for fld in td.FieldList:
            idx = fld.row_index
            fn = str(fields[idx - 1].Name)
            if fn == "value__":
                continue
            c = const_by_field.get(idx)
            val = number(c) if c is not None else None
            members.append((fn, val))
        if members:
            out.append((name, members))
    out.sort(key=lambda e: e[0])
    return out


def emit(enums, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "swconst.cs")
    lines = [
        "// Generated by tools/gen-swconst.py from the ModelForge swconst interop assembly.",
        "// The values are the SolidWorks constants the ModelForge C# workspace was compiled",
        "// against, read from that assembly's metadata. Do not edit by hand; regenerate with",
        "//   python3 tools/gen-swconst.py",
        "namespace ModelForge.Interop.swconst",
        "{",
    ]
    total = 0
    for name, members in enums:
        lines.append("    public enum %s" % name)
        lines.append("    {")
        for fn, val in members:
            if val is None:
                continue
            lines.append("        %s = %d," % (fn, val))
            total += 1
        lines.append("    }")
    lines.append("}")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return path, len(enums), total


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dll", default=DEFAULT_DLL)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "csharp", "SolidCraft.Interop", "swconst"))
    args = ap.parse_args()
    if not os.path.exists(args.dll):
        sys.exit("gen-swconst: no such assembly: %s" % args.dll)
    enums = load_enums(args.dll)
    path, enum_count, value_count = emit(enums, args.out)
    print("gen-swconst: wrote %d enums (%d constants) to %s" % (enum_count, value_count, path))


if __name__ == "__main__":
    main()
